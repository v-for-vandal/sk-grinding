#!/usr/bin/env python3
"""Insert / refresh an ASCII tree diagram (skill levels only) in every perk worksheet.

Reads the worksheets themselves (skills/*/*perks*.md), not the research tables:
- each `### <HANDLE> · <Name>` entry and its first `- **Requires:**` line (the winner);
- `#### Rank N` sub-entries (their skill level is shown on the parent line);
- `has perk <Name> (<HANDLE>)` gives the parents; `<Skill> ≥ N` gives the levels.

The diagram goes between DIAGRAM_BEGIN / DIAGRAM_END markers, before the first `##` heading.
Files that already have a hand-drawn `## Diagram` section without the markers are skipped
(e.g. skills/block, which also shows the planned requirements).

Usage: python3 scripts/gen_perk_diagrams.py [--dry-run] [files...]
"""
import glob
import re
import sys

BEGIN = "<!-- DIAGRAM_BEGIN (generated by scripts/gen_perk_diagrams.py) -->"
END = "<!-- DIAGRAM_END -->"

ENTRY_RE = re.compile(r"^### (?:(?P<handle>[A-Z0-9]+(?:-[A-Z0-9]+)+) · )?(?P<name>.+?)\s*$")
RANK_RE = re.compile(r"^#### Rank (?P<n>\d+)")
LEVEL_RE = re.compile(r"^([A-Z][A-Za-z'\-]*(?: [A-Z][A-Za-z'\-]*)*) ≥ (\d+)$")
PERK_RE = re.compile(r"has perk ([^()]+?) \(([^)]+)\)")
HANDLE_RE = re.compile(r"[A-Z0-9]+(?:-[A-Z0-9]+)+")


def parse(path):
    entries = []  # dict(handle, name, requires, ranks=[requires...])
    cur = None
    in_alt = False
    rank = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = ENTRY_RE.match(line)
        if m and not line.startswith("####"):
            cur = {"handle": m["handle"], "name": m["name"], "requires": None, "ranks": []}
            entries.append(cur)
            in_alt = False
            rank = None
            continue
        if cur is None:
            continue
        if line.startswith("#### Alternatives") or line.startswith("##### "):
            in_alt = True
            continue
        mr = RANK_RE.match(line)
        if mr:
            rank = {"n": int(mr["n"]), "requires": None}
            cur["ranks"].append(rank)
            in_alt = False
            continue
        if line.startswith("## "):
            cur = None
            continue
        if line.startswith("- **Requires:**") and not in_alt:
            req = line[len("- **Requires:**"):].strip()
            if rank is not None:
                if rank["requires"] is None:
                    rank["requires"] = req
            elif cur["requires"] is None:
                cur["requires"] = req
    return entries


def alt_requires(path):
    """For removed perks: first alternative that has a non-empty Requires, with its source."""
    out = {}
    cur = None
    src = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        m = ENTRY_RE.match(line)
        if m and not line.startswith("####"):
            cur = m["name"]
            src = None
            continue
        if line.startswith("##### "):
            src = line[6:].split(" · ")[0]
            continue
        if cur and src and cur not in out and line.startswith("- **Requires:**"):
            req = line[len("- **Requires:**"):].strip()
            if req and req != "—":
                out[cur] = (src, req)
    return out


def levels(req):
    if not req or req == "—":
        return []
    out = []
    for part in re.split(r" (?:AND|OR) ", req):
        m = LEVEL_RE.match(part.strip())
        if m:
            out.append(f"{m.group(1)} {m.group(2)}")
    return out


def parents(req):
    """[(handle_or_label, connector)] connector: 'AND' / 'OR' before this perk ref."""
    res = []
    if not req:
        return res
    for m in PERK_RE.finditer(req):
        name, ref = m.group(1).strip(), m.group(2).strip()
        before = req[: m.start()].rstrip()
        if before.endswith("not"):
            continue  # "not has perk X" is an exclusion, not a parent
        conn = "OR" if before.endswith("OR") else "AND"
        h = HANDLE_RE.search(ref)
        if ref.startswith("in LoreRim:") and h:
            res.append((f"[{name} = {h.group(0)}]", conn, True))
        elif h and h.group(0) == ref:
            res.append((ref, conn, False))
        else:
            res.append((f"[{name}]", conn, True))
    return res


def lvl_text(e):
    s = ", ".join(levels(e["requires"])) or "—"
    for r in e["ranks"]:
        rl = ", ".join(levels(r["requires"])) or "—"
        s += f"  (rank {r['n']}: {rl})"
    return s


def render_tree(entries):
    by = {}
    order = []
    for e in entries:
        key = e["handle"] or e["name"]
        by[key] = e
        order.append(key)
    par = {k: parents(by[k]["requires"]) for k in order}
    children = {k: [] for k in order}
    external = {}  # label -> [children]
    extra = {}
    roots = []
    for k in order:
        ps = [p for p in par[k] if p[0] != k]
        internal = [p for p in ps if p[0] in by]
        ext = [p for p in ps if p[0] not in by]
        if internal:
            first = internal[0][0]
            children[first].append(k)
            notes = [f"{'or' if c == 'OR' else 'also'} {h}" for h, c, _ in internal[1:] + ext]
        elif ext:
            external.setdefault(ext[0][0], []).append(k)
            notes = [f"{'or' if c == 'OR' else 'also'} {h}" for h, c, _ in ext[1:]]
        else:
            roots.append(k)
            notes = []
        extra[k] = notes

    lines = []
    seen = set()
    width = 46

    def label(k):
        e = by[k]
        t = f"{e['handle']} {e['name']}" if e["handle"] else e["name"]
        if extra[k]:
            t += " (" + "; ".join(extra[k]) + ")"
        return t

    def emit(k, prefix, last, top):
        if k in seen:
            return
        seen.add(k)
        branch = "" if top else ("└── " if last else "├── ")
        head = prefix + branch + label(k)
        dots = max(2, width - len(head))
        lines.append(f"{head} {'.' * dots} {lvl_text(by[k])}")
        kids = children[k]
        np = prefix + ("" if top else ("    " if last else "│   "))
        for i, c in enumerate(kids):
            emit(c, np, i == len(kids) - 1, False)

    for r in roots:
        emit(r, "", True, True)
    for lab, kids in external.items():
        lines.append(f"{lab} (in another worksheet)")
        for i, c in enumerate(kids):
            emit(c, "", i == len(kids) - 1, False)
    for k in order:  # cycles / leftovers
        if k not in seen:
            emit(k, "", True, True)
    return lines


def render_removed(path, entries):
    alts = alt_requires(path)
    lines = []
    for e in entries:
        name = e["name"]
        if name in alts:
            src, req = alts[name]
            ps = [h for h, _, _ in parents(req)]
            after = f" after {', '.join(ps)}" if ps else ""
            lv = ", ".join(levels(req)) or "—"
            lines.append(f"{name} .... {lv}{after}  [as in {src}]")
        else:
            lines.append(f"{name} .... —  [no requirements in any version]")
    return lines


def build(path):
    entries = parse(path)
    if not entries:
        return None
    if path.endswith("perks-removed.md"):
        body = render_removed(path, entries)
        intro = ("Generated from this file. Removed perks are not in the tree; each line shows the "
                 "skill levels (and parent perks) of the first earlier version that had any.")
    else:
        body = render_tree(entries)
        intro = ("Generated from the *Requires* lines of this file (winning version): parent perks "
                 "and skill levels only, other conditions omitted. A perk with several parents is "
                 "drawn under the first one (`also X` = AND, `or X` = OR); `[...]` = a perk of "
                 "another worksheet.")
    out = [BEGIN, "## Diagram (skill levels only)", "", intro, "", "```", *body, "```", END, ""]
    return "\n".join(out) + "\n"


def insert(path, block, dry):
    text = open(path, encoding="utf-8").read()
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        rest = text[b:].lstrip("\n")
        new = text[:a] + block + rest
    elif "## Diagram" in text:
        return "skip (hand-drawn diagram)"
    else:
        lines = text.split("\n")
        idx = next(i for i, l in enumerate(lines) if i > 0 and (l.startswith("## ") or l.startswith("### ")))
        new = "\n".join(lines[:idx]) + ("\n" if lines[idx - 1] == "" else "\n\n") + block + "\n" + "\n".join(lines[idx:])
    if dry:
        print(block)
    elif new != text:
        open(path, "w", encoding="utf-8").write(new)
    return "ok"


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dry = "--dry-run" in sys.argv
    files = args or sorted(glob.glob("skills/*/*perks*.md"))
    for f in files:
        block = build(f)
        if block is None:
            print(f"{f}: no entries")
            continue
        print(f"{f}: {insert(f, block, dry)}")


if __name__ == "__main__":
    main()
